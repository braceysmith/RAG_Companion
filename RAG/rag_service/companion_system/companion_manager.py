# Configure logging
logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

@dataclass
class UserAccount:
    """User account with associated companions and preferences"""
    user_id: str
    username: str
    email: str
    created_at: datetime
    last_login: datetime
    preferences: Dict[str, Any] = field(default_factory=dict)
    active_companion_id: Optional[str] = None
    companion_ids: List[str] = field(default_factory=list)
    settings: Dict[str, Any] = field(default_factory=dict)
    
    def add_companion(self, companion_id: str) -> None:
        """Add a companion to the user's library"""
        if companion_id not in self.companion_ids:
            self.companion_ids.append(companion_id)
    
    def remove_companion(self, companion_id: str) -> bool:
        """Remove a companion from the user's library"""
        if companion_id in self.companion_ids:
            self.companion_ids.remove(companion_id)
            if self.active_companion_id == companion_id:
                self.active_companion_id = None
            return True
        return False
    
    def set_active_companion(self, companion_id: str) -> bool:
        """Set the active companion for the user"""
        if companion_id in self.companion_ids:
            self.active_companion_id = companion_id
            return True
        return False
    
    def update_login(self) -> None:
        """Update last login time"""
        self.last_login = datetime.now()
    
    def to_dict(self) -> Dict:
        """Convert to dictionary"""
        return {
            "user_id": self.user_id,
            "username": self.username,
            "email": self.email,
            "created_at": self.created_at.isoformat(),
            "last_login": self.last_login.isoformat(),
            "preferences": self.preferences,
            "active_companion_id": self.active_companion_id,
            "companion_ids": self.companion_ids,
            "settings": self.settings
        }
    
    @classmethod
    def from_dict(cls, data: Dict) -> 'UserAccount':
        """Create from dictionary"""
        return cls(
            user_id=data["user_id"],
            username=data["username"],
            email=data["email"],
            created_at=datetime.fromisoformat(data["created_at"]),
            last_login=datetime.fromisoformat(data["last_login"]),
            preferences=data.get("preferences", {}),
            active_companion_id=data.get("active_companion_id"),
            companion_ids=data.get("companion_ids", []),
            settings=data.get("settings", {})
        )

@dataclass
class GeneratedContent:
    """Content generated by a companion"""
    content_id: str
    companion_id: str
    user_id: str
    content_type: str  # text, image, audio, etc.
    title: str
    content: str
    metadata: Dict[str, Any]
    created_at: datetime
    tags: List[str] = field(default_factory=list)
    is_public: bool = False
    
    def to_dict(self) -> Dict:
        """Convert to dictionary"""
        return {
            "content_id": self.content_id,
            "companion_id": self.companion_id,
            "user_id": self.user_id,
            "content_type": self.content_type,
            "title": self.title,
            "content": self.content,
            "metadata": self.metadata,
            "created_at": self.created_at.isoformat(),
            "tags": self.tags,
            "is_public": self.is_public
        }
    
    @classmethod
    def from_dict(cls, data: Dict) -> 'GeneratedContent':
        """Create from dictionary"""
        return cls(
            content_id=data["content_id"],
            companion_id=data["companion_id"],
            user_id=data["user_id"],
            content_type=data["content_type"],
            title=data["title"],
            content=data["content"],
            metadata=data.get("metadata", {}),
            created_at=datetime.fromisoformat(data["created_at"]),
            tags=data.get("tags", []),
            is_public=data.get("is_public", False)
        )


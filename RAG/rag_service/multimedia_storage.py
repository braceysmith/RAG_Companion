    async def store_content_with_embedding(self, source_path: str, user_id: str, 
                                         content_description: str, embedding: List[float],
                                         content_type: str = None, session_id: str = None,
                                         turn_id: str = None, metadata: Dict = None,
                                         is_generated: bool = False, generation_tool: str = None,
                                         generation_prompt: str = None, tags: List[str] = None) -> str:
        """
        Store multimedia content with vector embedding for semantic search
        
        Args:
            source_path: Path to source file
            user_id: User identifier
            content_description: Text description for vector embedding
            embedding: Vector embedding of the content description
            content_type: Type of content (auto-detected if None)
            session_id: Conversation session ID
            turn_id: Conversation turn ID
            metadata: Additional metadata
            is_generated: Whether content was generated by MCP tool
            generation_tool: Name of MCP tool that generated content
            generation_prompt: Prompt used to generate content
            tags: Content tags for categorization
            
        Returns:
            Content ID of stored file
        """
        try:
            # First store the file normally
            content_id = self.store_file(
                source_path=source_path,
                user_id=user_id,
                content_type=content_type,
                session_id=session_id,
                turn_id=turn_id,
                metadata=metadata,
                is_generated=is_generated,
                generation_tool=generation_tool,
                generation_prompt=generation_prompt,
                tags=tags
            )
            
            # Then store the description and embedding in pgvector table
            if self.database:
                await self.database.store_multimedia_embedding(
                    content_id=content_id,
                    user_id=user_id,
                    description=content_description,
                    embedding=embedding,
                    content_type=content_type or self._detect_content_type(source_path),
                    metadata=metadata or {}
                )
            
            return content_id
            
        except Exception as e:
            logger.error(f"Error storing content with embedding: {e}")
            raise
    
    async def search_multimedia_by_similarity(self, query_embedding: List[float], 
                                            user_id: str = None, content_type: str = None,
                                            top_k: int = 5) -> List[Dict[str, Any]]:
        """
        Search multimedia content using vector similarity
        
        Args:
            query_embedding: Vector embedding of search query
            user_id: Filter by specific user (optional)
            content_type: Filter by content type (optional)
            top_k: Number of results to return
            
        Returns:
            List of similar multimedia content with similarity scores
        """
        if not self.database:
            return []
        
        try:
            results = await self.database.search_multimedia_embeddings(
                query_embedding=query_embedding,
                user_id=user_id,
                content_type=content_type,
                top_k=top_k
            )
            
            # Enrich results with file information
            enriched_results = []
            for result in results:
                content = self.get_content(result["content_id"])
                if content:
                    enriched_results.append({
                        **result,
                        "file_path": content.file_path,
                        "file_name": content.file_name,
                        "file_size": content.file_size,
                        "mime_type": content.mime_type,
                        "is_generated": content.is_generated,
                        "generation_tool": content.generation_tool,
                        "tags": content.tags
                    })
            
            return enriched_results
            
        except Exception as e:
            logger.error(f"Error searching multimedia by similarity: {e}")
            return []
    
    async def get_content_recommendations(self, user_id: str, content_id: str = None,
                                        content_type: str = None, top_k: int = 5) -> List[Dict[str, Any]]:
        """
        Get content recommendations based on user's content history
        
        Args:
            user_id: User identifier
            content_id: Use specific content as reference (optional)
            content_type: Filter by content type (optional)
            top_k: Number of recommendations to return
            
        Returns:
            List of recommended content
        """
        if not self.database:
            return []
        
        try:
            # Get user's recent content
            user_content = self.get_user_content(user_id, content_type=content_type, limit=10)
            
            if not user_content:
                return []
            
            # Use the most recent content or specified content as reference
            reference_content = None
            if content_id:
                reference_content = self.get_content(content_id)
            
            if not reference_content:
                reference_content = user_content[0]
            
            # Get embedding for reference content
            embedding = await self.database.get_multimedia_embedding(reference_content.content_id)
            if not embedding:
                return []
            
            # Find similar content
            similar_content = await self.search_multimedia_by_similarity(
                query_embedding=embedding,
                user_id=user_id,
                content_type=content_type,
                top_k=top_k + 1  # +1 to exclude the reference content
            )
            
            # Filter out the reference content
            recommendations = [
                content for content in similar_content 
                if content["content_id"] != reference_content.content_id
            ][:top_k]
            
            return recommendations
            
        except Exception as e:
            logger.error(f"Error getting content recommendations: {e}")
            return []
    
